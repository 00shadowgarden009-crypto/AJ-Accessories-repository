-- AJ Accessories shared catalogue and order database
-- Run this once in Supabase Dashboard > SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  category text not null check (char_length(category) between 1 and 50),
  price integer not null check (price > 0),
  emoji text not null default '📦',
  description text not null default '',
  tag text not null default '',
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null check (char_length(customer_name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 254),
  phone text not null check (char_length(phone) between 3 and 30),
  address text not null check (char_length(address) between 3 and 500),
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  total integer not null check (total > 0),
  status text not null default 'pending' check (status in ('pending','confirmed','fulfilled','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.store_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_store_admin()
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (select 1 from public.store_admins where user_id = auth.uid());
$$;
revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to anon, authenticated;

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.store_admins enable row level security;

drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products" on public.products for select to anon, authenticated using (active or public.is_store_admin());
drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products" on public.products for insert to authenticated with check (public.is_store_admin());
drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products" on public.products for update to authenticated using (public.is_store_admin()) with check (public.is_store_admin());
drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products" on public.products for delete to authenticated using (public.is_store_admin());

drop policy if exists "Admins can view orders" on public.orders;
create policy "Admins can view orders" on public.orders for select to authenticated using (public.is_store_admin());
drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders" on public.orders for update to authenticated using (public.is_store_admin()) with check (public.is_store_admin());
-- No direct public order insert policy: all order placement goes through the
-- validating, stock-locking RPC below. Customer PII is not publicly readable.

create or replace function public.place_store_order(
  p_customer_name text,
  p_email text,
  p_phone text,
  p_address text,
  p_items jsonb
) returns uuid
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  item jsonb;
  product_row public.products%rowtype;
  qty integer;
  running_total integer := 0;
  item_snapshot jsonb := '[]'::jsonb;
  new_order_id uuid;
begin
  if length(trim(coalesce(p_customer_name,''))) not between 1 and 100
    or length(trim(coalesce(p_email,''))) not between 3 and 254
    or length(trim(coalesce(p_phone,''))) not between 3 and 30
    or length(trim(coalesce(p_address,''))) not between 3 and 500 then
    raise exception 'Please provide valid contact and delivery details.';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 30 then
    raise exception 'Your bag is empty or contains too many different products.';
  end if;
  for item in select value from jsonb_array_elements(p_items) loop
    if (item->>'product_id') !~ '^[0-9]+$' or (item->>'quantity') !~ '^[0-9]+$' then
      raise exception 'Invalid product or quantity.';
    end if;
    qty := (item->>'quantity')::integer;
    if qty < 1 or qty > 20 then raise exception 'Quantity must be between 1 and 20.'; end if;
    select * into product_row from public.products where id = (item->>'product_id')::bigint and active = true for update;
    if not found then raise exception 'A product in your bag is no longer available.'; end if;
    if product_row.stock < qty then raise exception 'There is not enough stock for %.', product_row.name; end if;
    update public.products set stock = stock - qty where id = product_row.id;
    running_total := running_total + product_row.price * qty;
    item_snapshot := item_snapshot || jsonb_build_array(jsonb_build_object('product_id', product_row.id, 'name', product_row.name, 'quantity', qty, 'unit_price', product_row.price));
  end loop;
  insert into public.orders(customer_name,email,phone,address,items,total)
    values(trim(p_customer_name),trim(p_email),trim(p_phone),trim(p_address),item_snapshot,running_total)
    returning id into new_order_id;
  return new_order_id;
end;
$$;
revoke all on function public.place_store_order(text,text,text,text,jsonb) from public;
grant execute on function public.place_store_order(text,text,text,text,jsonb) to anon, authenticated;

